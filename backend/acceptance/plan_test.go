// Task 2.6: the DNS plan we hand an operator agrees, record for record, with
// the zone the issuance actually validated against.
//
// WHAT IS COMPARED, AND WHAT IS DELIBERATELY NOT.
//
// Only the `_acme-challenge` alias records are compared, and those exactly, in
// both directions: every alias record the plan emits must exist in the zone and
// every one in the zone must be in the plan. For the seeded inventory that is
// the single
//
//	_acme-challenge.demo.example.com. CNAME demo-example-com.dev.acmeservice.internal.
//
// which is the one record the issuance under test validated against — with the
// label the running service generated, since the zone file is itself rendered
// from `adminctl loadbalancer dns demo/prod` by development/scripts/seed.sh.
// That the two sides share a source does not make the comparison empty: the
// seed copies only the challenge rows, through a text pipeline, into a zone
// CoreDNS then has to parse and serve, and this asserts that round trip.
//
// The zone's ADDRESS records are excluded ON PURPOSE, and the zone file says so
// itself: it points demo/*.demo at the traefik-lb container (172.28.0.30)
// because something has to actually answer, while the plan prints the seeded
// node addresses (203.0.113.10/.11 — TEST-NET-3, unroutable by design).
// Asserting those equal would assert a falsehood. The exclusion is stated here
// rather than achieved by quietly diffing a subset, which is how a comparison
// stops covering anything without anyone noticing.
func TestGeneratedPlanMatchesTheServedZone(t *testing.T) {
	planned := challengeRecords(t, planRecords(t))
	served := challengeRecords(t, zoneFileRecords(t))

	if len(planned) == 0 {
		t.Fatal("the generated plan contains no _acme-challenge record at all")
	}
	slices.Sort(planned)
	slices.Sort(served)
	if !slices.Equal(planned, served) {
		t.Fatalf("the generated plan and the served zone disagree on the challenge alias records\n"+
			"  plan:  %v\n  zone:  %v\n"+
			"development/dns/zones/example.com.zone is generated by "+
			"development/scripts/seed.sh from this very plan, so a disagreement means the "+
			"zone was not re-rendered after the inventory changed — issuance then fails "+
			"with an NXDOMAIN pointing nowhere near the cause", planned, served)
	}
}

// challengeRecords keeps only the _acme-challenge records and renders each as a
// comparable string. TTLs are dropped: the plan suggests one, the zone file
// chooses its own, and neither is what this assertion is about.
func challengeRecords(t *testing.T, rrs []dns.RR) []string {
	t.Helper()
	var out []string
	for _, rr := range rrs {
		if !strings.HasPrefix(rr.Header().Name, "_acme-challenge.") {
			continue
		}
		c, ok := rr.(*dns.CNAME)
		if !ok {
			t.Fatalf("unexpected %s record at %s; challenge aliases are CNAMEs",
				dns.TypeToString[rr.Header().Rrtype], rr.Header().Name)
		}
		out = append(out, c.Hdr.Name+" CNAME "+c.Target)
	}
	return out
}

// planRecords runs the CLI the way an operator does — inside the api container,
// where the toolchain and the database view live — and parses the zone snippet
// it prints.
func planRecords(t *testing.T) []dns.RR {
	t.Helper()
	out := compose(t, "exec", "-T", "api", "go", "run", "./cmd/acmeservice",
		"adminctl", "loadbalancer", "dns", "demo/prod")

	_, snippet, ok := strings.Cut(out, "Zone snippet:")
	if !ok {
		t.Fatalf("`adminctl loadbalancer dns demo/prod` printed no zone snippet:\n%s", out)
	}
	var rrs []dns.RR
	for _, line := range strings.Split(snippet, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, ";") {
			continue
		}
		rr, err := dns.NewRR(line)
		if err != nil {
			t.Fatalf("cannot parse a line of the generated zone snippet as a record: %q: %v", line, err)
		}
		rrs = append(rrs, rr)
	}
	return rrs
}

// zoneFileRecords parses the zone CoreDNS is actually serving.
func zoneFileRecords(t *testing.T) []dns.RR {
	t.Helper()
	path := filepath.Join(repoDir, "development/dns/zones/example.com.zone")
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("opening %s: %v", path, err)
	}
	defer f.Close()

	var rrs []dns.RR
	zp := dns.NewZoneParser(f, "example.com.", path)
	for rr, ok := zp.Next(); ok; rr, ok = zp.Next() {
		rrs = append(rrs, rr)
	}
	if err := zp.Err(); err != nil {
		t.Fatalf("parsing %s: %v", path, err)
	}
	return rrs
}
