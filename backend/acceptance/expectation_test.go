// What a domain needs published in somebody else's zone, read back off the
// DOMAIN (change domain-diagnostics, tasks 10.1, 10.2, 11.9).
//
// This file was plan_test.go and asserted the same thing about a project-wide
// record table served at /projects/{id}/plan and printed by `adminctl project
// dns`. Both are gone: which records a domain needs is a property of that
// domain, and answering it twice — once per record and once per domain — gave
// two views of one fact that could be read and believed after the other had
// moved on (G2). The assertion worth keeping was never about the plan, and it
// is restated below against `cnameTarget`.

// TestTheDomainReadMatchesTheServedZone: the CNAME target this service tells a
// customer to publish is the one its own zone answers for.
//
// WHAT IS COMPARED, AND WHAT IS DELIBERATELY NOT.
//
// Only the `_acme-challenge` alias records, and those exactly, in both
// directions: every target the domain read hands out must exist in the fake
// internet's zone and every alias record in that zone must be one the domain
// read named. For the seeded inventory that is two records for three domains,
// because demo.example.com and *.demo.example.com share one alias.
//
// That the two sides share a source does not make the comparison empty:
// development/scripts/seed.sh copies the targets out of the database through a
// shell pipeline into a zone file CoreDNS then has to parse and serve, and this
// asserts that round trip. It is also what delegation_test.go's onboardDomain
// depends on — it renders the same target into the same zone — so a drift
// between the two would silently stop every domain in this suite activating.
//
// The zone's ADDRESS records are excluded ON PURPOSE, and the zone file says so
// itself: it points demo/*.demo/alt at the traefik-lb container (172.28.0.30)
// because something has to actually answer, while the seeded nodes carry
// TEST-NET-3 addresses that are unroutable by design. Asserting those equal
// would assert a falsehood. The exclusion is stated here rather than achieved by
// quietly diffing a subset, which is how a comparison stops covering anything
// without anyone noticing.
func TestTheDomainReadMatchesTheServedZone(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	domains := projectDomains(t, s, demoProject(t, s))

	// Deduplicated, because the record set is per ALIAS and the domain set is
	// per domain: the wildcard and its apex name one record between them, and a
	// comparison that let it appear twice would be asserting how many domains
	// happen to share it.
	expected := map[string]bool{}
	for _, d := range domains {
		if d.CNAMETarget == "" {
			continue // no alias: nothing to publish, and 12.17's case
		}
		expected[dns.Fqdn(d.ChallengeName)+" CNAME "+dns.Fqdn(d.CNAMETarget)] = true
	}
	planned := slices.Sorted(maps.Keys(expected))
	served := challengeRecords(t, zoneFileRecords(t))

	if len(planned) == 0 {
		t.Fatal("no domain of the seeded project names a CNAME target at all")
	}
	slices.Sort(served)
	if !slices.Equal(planned, served) {
		t.Fatalf("the targets the domain read hands out and the served zone disagree\n"+
			"  domains:  %v\n  zone:     %v\n"+
			"development/dns/zones/example.com.zone is generated by "+
			"development/scripts/seed.sh from these very targets, so a disagreement means "+
			"the zone was not re-rendered after the inventory changed — issuance then "+
			"fails with an NXDOMAIN pointing nowhere near the cause", planned, served)
	}
}

// TestADomainCarriesWhatItNeedsPublished is 12.16, 12.17 and half of 12.18: the
// per-domain expectation, asserted where the plan's own table used to be.
//
// The wildcard-and-apex invariant is the one the whole design turns on. Two
// domains, one alias, ONE record to publish — a customer who is told to publish
// two has been told to publish one they cannot, since a second CNAME at the same
// name is not a thing DNS allows.
func TestADomainCarriesWhatItNeedsPublished(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	project := demoProject(t, s)
	domains := projectDomains(t, s, project)

	byName := map[string]domainDetail{}
	for _, d := range domains {
		byName[d.Name] = d
	}
	apex, ok := byName[demoDomain]
	if !ok {
		t.Fatalf("the seeded project has no %s; it holds %v", demoDomain, byName)
	}
	wildcard, ok := byName[wildcardDomain]
	if !ok {
		t.Fatalf("the seeded project has no %s; it holds %v", wildcardDomain, byName)
	}

	// 12.16. Same alias, same challenge name, same target — asserted on the two
	// DOMAINS rather than on one record row, which is the whole shape change.
	if apex.CNAMETarget == "" {
		t.Fatalf("%s names no CNAME target; every domain with an alias has one", demoDomain)
	}
	if apex.CNAMETarget != wildcard.CNAMETarget {
		t.Errorf("%s points at %q and %s at %q — a wildcard and its apex derive one challenge "+
			"name, share one alias and therefore need ONE record published between them (D6)",
			demoDomain, apex.CNAMETarget, wildcardDomain, wildcard.CNAMETarget)
	}
	if apex.ChallengeName != wildcard.ChallengeName || apex.AliasID != wildcard.AliasID {
		t.Errorf("%s and %s disagree about their challenge name (%q / %q) or alias (%s / %s); "+
			"the shared target above is then a coincidence rather than the invariant",
			demoDomain, wildcardDomain, apex.ChallengeName, wildcard.ChallengeName,
			apex.AliasID, wildcard.AliasID)
	}
	// And a third domain in the same project, which is what makes the equality
	// above worth something: sharing a target is a property of the pair, not of
	// the project.
	if alt, ok := byName["alt.example.com"]; ok && alt.CNAMETarget == apex.CNAMETarget {
		t.Errorf("alt.example.com and %s share the target %q; they derive different challenge "+
			"names and must have different aliases", demoDomain, alt.CNAMETarget)
	}

	// 12.16, the CAA half. This deployment configures no issuer
	// (ACME_CAA_ISSUER unset), so the honest assertion is not "there are entries"
	// — it is that the domain read and the verification agree about whether
	// there are, and about what they say. A console draws its CAA dot from the
	// first and its status from the second, and one of them growing an issuer
	// the other has not is exactly the disagreement a customer cannot debug.
	checks := verification(t, s, project)
	for _, d := range domains {
		got := checks[strings.TrimSuffix(d.Name, ".")]
		switch {
		case len(d.ExpectedCAA) == 0 && got.CAA != nil:
			t.Errorf("%s carries no expectedCaa and the verification answers a CAA check "+
				"(%v) — the console would hide the dot for a record the service is grading",
				d.Name, got.CAA.Expected)
		case len(d.ExpectedCAA) > 0 && got.CAA == nil:
			t.Errorf("%s expects CAA %v and the verification answers none for it",
				d.Name, d.ExpectedCAA)
		case len(d.ExpectedCAA) > 0 && !slices.Equal(d.ExpectedCAA, got.CAA.Expected):
			t.Errorf("%s expects CAA %v from the domain read and %v from the verification",
				d.Name, d.ExpectedCAA, got.CAA.Expected)
		}
	}
}

// TestEveryDomainCarriesACNAMETargetFieldEvenWithNone is 12.17.
//
// A domain whose alias has gone missing is still RETURNED, carrying no target,
// rather than dropped from the list — and the field is present and empty rather
// than omitted. The distinction is not pedantry: an omitted key is what an older
// service that never had the field would send, so a console reading `undefined`
// cannot tell "this deployment does not answer the question" from "there is no
// alias yet", and those want different words on the screen.
//
// Acceptance cannot manufacture an aliasless domain — every creation makes or
// finds one — so what is asserted here is the property that makes the absence
// SAYABLE, on every domain the stack has. internal/inventory's
// TestExpectationDomainWithoutAliasStillAppears covers the row itself, a level
// down and far cheaper.
func TestEveryDomainCarriesACNAMETargetFieldEvenWithNone(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	raw := projectDomainsJSON(t, s, demoProject(t, s))

	var rows []map[string]json.RawMessage
	if err := json.Unmarshal(raw, &rows); err != nil {
		t.Fatalf("decoding the domain list as objects: %v", err)
	}
	if len(rows) == 0 {
		t.Fatal("the seeded project answers no domains")
	}
	for _, row := range rows {
		if _, ok := row["cnameTarget"]; !ok {
			t.Errorf("a domain answers no cnameTarget key at all: %v — an omitted field is "+
				"indistinguishable from a service that predates it, which is the one thing "+
				"this field exists to be able to say (10.1)", row)
		}
	}
}

// TestTheDomainReadGradesNothingAgainstTheCustomersOwnAddresses is the other
// half of 12.18, and it is 11.5's decision rather than a shape check.
//
// The plan used to carry an A and an AAAA row per node, checked against DNS. A
// customer typed those addresses into the Nodes panel on the same screen, so the
// only finding that check could ever produce was that the customer disagrees
// with the customer (G2). They are gone, and the assertion that they stay gone
// is that no address of the project's own nodes appears anywhere in what the
// domain read answers.
func TestTheDomainReadGradesNothingAgainstTheCustomersOwnAddresses(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	project := demoProject(t, s)

	var detail struct {
		Nodes []struct {
			Label string  `json:"label"`
			IPv4  *string `json:"ipv4"`
			IPv6  *string `json:"ipv6"`
		} `json:"nodes"`
	}
	if err := s.getJSON(s.acct("/projects/"+project), &detail); err != nil {
		t.Fatalf("reading the seeded project: %v", err)
	}
	if len(detail.Nodes) == 0 {
		t.Fatal("the seeded project has no nodes, so this test can prove nothing")
	}

	raw := projectDomainsJSON(t, s, project)
	for _, n := range detail.Nodes {
		for _, addr := range []*string{n.IPv4, n.IPv6} {
			if addr == nil || *addr == "" {
				continue
			}
			if bytes.Contains(raw, []byte(*addr)) {
				t.Errorf("the domain read mentions %s, the address of node %q — the address "+
					"records are gone and are not to be relocated: grading a customer's DNS "+
					"against addresses that customer typed in has one possible finding, which "+
					"is that they disagree with themselves (11.5, G2)\n%s", *addr, n.Label, raw)
			}
		}
	}
}

// TestThePlanEndpointsAreGone is the first half of 12.18.
//
// 404 and not 405 or 501: the routes are unregistered, which is what makes a
// console still asking for them fail loudly and immediately. SEQUENCE.md puts
// the first customers at step 13 and this is step 14's predecessor, so removing
// a published path here is a rename rather than a deprecation (11.10) — and this
// is the test that says the rename actually happened.
func TestThePlanEndpointsAreGone(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	project := demoProject(t, s)

	for _, path := range []string{"/projects/" + project + "/plan", "/projects/" + project + "/plan/zone"} {
		status, body, err := s.do(http.MethodGet, s.acct(path), nil)
		if err != nil {
			t.Fatalf("GET %s: %v", path, err)
		}
		if status != http.StatusNotFound {
			t.Errorf("GET %s: got %d, want 404 — the DNS plan is gone and what replaced it is "+
				"a property of each domain (11.4): %s", path, status, body)
		}
	}
}

// TestVerificationAnswersPerDomainAndNotPerRecord is 12.19.
//
// The `results` array said the same thing as `domains`, keyed by record instead
// of by domain, and only the per-domain keying ever had a reader (11.7, G2). Its
// absence is asserted on the BODY rather than on a decode, because a struct
// without the field decodes a response that still carries it perfectly happily —
// which is how a dropped field stays in a payload for a year.
func TestVerificationAnswersPerDomainAndNotPerRecord(t *testing.T) {
	s := mustSignInSeeded(t, adminUser)
	project := demoProject(t, s)

	status, raw, err := s.do(http.MethodGet, s.acct("/projects/"+project+"/verification"), nil)
	if err != nil {
		t.Fatalf("reading the verification: %v", err)
	}
	if status != http.StatusOK {
		t.Fatalf("reading the verification: got %d, want 200: %s", status, raw)
	}
	var body map[string]json.RawMessage
	if err := json.Unmarshal(raw, &body); err != nil {
		t.Fatalf("decoding the verification: %v", err)
	}
	if _, ok := body["results"]; ok {
		t.Errorf("the verification still carries a `results` array: %s — it answers the same "+
			"pass keyed a second way, and a second view of one fact is a second thing that "+
			"can be believed after the first has moved on (11.7)", raw)
	}
	if _, ok := body["domains"]; !ok {
		t.Errorf("the verification carries no `domains`: %s — the per-domain half is the half "+
			"that stays", raw)
	}
	// And it is not merely present but empty: the seeded project has domains,
	// and a `domains: []` beside a removed `results` would be the reshape
	// deleting both halves.
	var domains []acceptanceDomainCheck
	if err := json.Unmarshal(body["domains"], &domains); err != nil {
		t.Fatalf("decoding the per-domain answers: %v", err)
	}
	if len(domains) == 0 {
		t.Errorf("the verification answers no domains for the seeded project: %s", raw)
	}
}

// --- reading domains -------------------------------------------------------

// domainDetail is the domain read as this suite addresses it. It is domainRef
// plus the two fields the plan used to carry, kept as a separate type because
// domainRef is what the arc tests pass around and adding the expectation to it
// would make every one of them look like it cared.
type domainDetail struct {
	ID            string   `json:"id"`
	Name          string   `json:"name"`
	ChallengeName string   `json:"challengeName"`
	AliasID       string   `json:"aliasId"`
	CNAMETarget   string   `json:"cnameTarget"`
	ExpectedCAA   []string `json:"expectedCaa"`
	ObserveTLS    bool     `json:"observeTls"`
	TLSTestHost   *string  `json:"tlsTestHost"`
}

func projectDomains(t *testing.T, s *session, project string) []domainDetail {
	t.Helper()
	var out []domainDetail
	if err := json.Unmarshal(projectDomainsJSON(t, s, project), &out); err != nil {
		t.Fatalf("decoding the domains of %s: %v", project, err)
	}
	return out
}

// projectDomainsJSON is the same read left undecoded, for the assertions that
// are about what is IN the payload rather than about what decodes out of it.
func projectDomainsJSON(t *testing.T, s *session, project string) []byte {
	t.Helper()
	status, raw, err := s.do(http.MethodGet, s.acct("/projects/"+project+"/domains"), nil)
	if err != nil {
		t.Fatalf("listing the domains of %s: %v", project, err)
	}
	if status != http.StatusOK {
		t.Fatalf("listing the domains of %s: got %d, want 200: %s", project, status, raw)
	}
	return raw
}

// --- reading the served zone -----------------------------------------------

// challengeRecords keeps only the _acme-challenge records of a zone and renders
// each as a comparable string. TTLs are dropped: the zone file chooses one and
// the domain read suggests none, and neither is what this is about.
func challengeRecords(t *testing.T, rrs []dns.RR) []string {
	t.Helper()
	var out []string
	for _, rr := range rrs {
		if !strings.HasPrefix(rr.Header().Name, "_acme-challenge.") {
			continue
		}
		c, ok := rr.(*dns.CNAME)
		if !ok {
			t.Fatalf("unexpected %s record at %s; challenge aliases are CNAMEs",
				dns.TypeToString[rr.Header().Rrtype], rr.Header().Name)
		}
		out = append(out, c.Hdr.Name+" CNAME "+c.Target)
	}
	return out
}

// zoneFileRecords parses the zone CoreDNS is actually serving. delegation_test.go
// reads it too, to add and restore the delegations its domains need.
func zoneFileRecords(t *testing.T) []dns.RR {
	t.Helper()
	path := filepath.Join(repoDir, "development/dns/zones/example.com.zone")
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("opening %s: %v", path, err)
	}
	defer f.Close()

	var rrs []dns.RR
	zp := dns.NewZoneParser(f, "example.com.", path)
	for rr, ok := zp.Next(); ok; rr, ok = zp.Next() {
		rrs = append(rrs, rr)
	}
	if err := zp.Err(); err != nil {
		t.Fatalf("parsing %s: %v", path, err)
	}
	return rrs
}
